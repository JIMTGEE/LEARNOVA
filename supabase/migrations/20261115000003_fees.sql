-- =====================================================================
-- Fees and payments
--
-- Legacy mapping
--   fees (target Class / Learner / School) -> fee_types + one student_fees row per learner.
--     "Assigning" a fee to a class or the whole school creates those rows.
--   debts                                  -> not stored. Derived: student_fee_balances.
--   payments                               -> payments (append-only; mistakes are voided)
--   receipts                               -> payments.receipt_number (a receipt is 1:1 with a payment)
--
-- Money rules
--   * Payments cannot be edited or deleted. A wrong payment is voided with a reason.
--   * A payment can only point at a fee that belongs to the same learner and school
--     (composite foreign key).
--   * Receipt numbers are generated by the database, per school, without gaps from races.
-- =====================================================================

create type public.payment_method as enum
  ('cash', 'momo', 'bank_transfer', 'card', 'cheque', 'other');

create function private.is_finance_viewer()
returns boolean language sql stable security definer set search_path = ''
as $$ select coalesce(private.app_role() in ('admin', 'headmaster', 'accountant'), false) $$;

create function private.can_manage_finance()
returns boolean language sql stable security definer set search_path = ''
as $$ select coalesce(private.app_role() in ('admin', 'accountant'), false) $$;

grant execute on function private.is_finance_viewer() to authenticated;
grant execute on function private.can_manage_finance() to authenticated;

create table public.fee_types (
  id           uuid primary key default gen_random_uuid(),
  school_id    uuid not null references public.schools (id) on delete cascade,
  name         text not null,
  description  text,
  is_recurring boolean not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now(),
  unique (school_id, name),
  unique (id, school_id)
);

create table public.student_fees (
  id               uuid primary key default gen_random_uuid(),
  school_id        uuid not null references public.schools (id) on delete cascade,
  student_id       uuid not null,
  fee_type_id      uuid not null,
  academic_year_id uuid not null,
  term_id          uuid,
  amount_due       numeric(10,2) not null check (amount_due >= 0),
  due_date         date,
  note             text,
  created_by       uuid default auth.uid() references public.profiles (id) on delete set null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  unique (id, school_id),
  unique (id, student_id, school_id),
  foreign key (student_id, school_id)
    references public.students (id, school_id) on delete restrict,
  foreign key (fee_type_id, school_id)
    references public.fee_types (id, school_id) on delete restrict,
  foreign key (academic_year_id, school_id)
    references public.academic_years (id, school_id) on delete restrict,
  foreign key (term_id, school_id)
    references public.terms (id, school_id) on delete restrict
);
create index student_fees_student_idx on public.student_fees (student_id, academic_year_id);

create table public.payments (
  id             uuid primary key default gen_random_uuid(),
  school_id      uuid not null references public.schools (id) on delete cascade,
  student_id     uuid not null,
  student_fee_id uuid,
  amount         numeric(10,2) not null check (amount > 0),
  paid_on        date not null default current_date,
  method         public.payment_method not null,
  reference      text,                 -- MoMo transaction id, bank slip number, cheque number
  receipt_number text not null,
  recorded_by    uuid default auth.uid() references public.profiles (id) on delete set null,
  voided_at      timestamptz,
  void_reason    text,
  created_at     timestamptz not null default now(),
  unique (school_id, receipt_number),
  check (voided_at is null or void_reason is not null),
  foreign key (student_id, school_id)
    references public.students (id, school_id) on delete restrict,
  -- when student_fee_id is set, the fee must belong to the same learner and school
  foreign key (student_fee_id, student_id, school_id)
    references public.student_fees (id, student_id, school_id) on delete restrict
);
create index payments_student_idx on public.payments (student_id, paid_on desc);
create index payments_fee_idx on public.payments (student_fee_id);

-- ---------------------------------------------------------------------
-- Receipt numbers: RC-2026-000001, counted per school
-- ---------------------------------------------------------------------
create table private.receipt_counters (
  school_id  uuid primary key references public.schools (id) on delete cascade,
  last_value bigint not null default 0
);
alter table private.receipt_counters enable row level security;

create function private.next_receipt_number(p_school uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  n bigint;
begin
  insert into private.receipt_counters (school_id, last_value)
  values (p_school, 1)
  on conflict (school_id)
    do update set last_value = private.receipt_counters.last_value + 1
  returning last_value into n;

  return 'RC-' || to_char(now(), 'YYYY') || '-' || lpad(n::text, 6, '0');
end;
$$;

create function private.set_receipt_number()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.receipt_number is null or new.receipt_number = '' then
    new.receipt_number := private.next_receipt_number(new.school_id);
  end if;
  return new;
end;
$$;

create trigger payments_set_receipt
  before insert on public.payments
  for each row execute function private.set_receipt_number();

create trigger set_updated_at before update on public.fee_types
  for each row execute function private.set_updated_at();
create trigger set_updated_at before update on public.student_fees
  for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------------
-- What a learner owes. Voided payments do not count.
-- ---------------------------------------------------------------------
create view public.student_fee_balances
with (security_invoker = true) as
select
  sf.id                                                        as student_fee_id,
  sf.school_id,
  sf.student_id,
  sf.fee_type_id,
  sf.academic_year_id,
  sf.term_id,
  sf.due_date,
  sf.amount_due,
  coalesce(sum(p.amount), 0)::numeric(10,2)                    as amount_paid,
  (sf.amount_due - coalesce(sum(p.amount), 0))::numeric(10,2)  as balance
from public.student_fees sf
left join public.payments p
  on p.student_fee_id = sf.id
 and p.school_id = sf.school_id
 and p.voided_at is null
group by sf.id;

-- ---------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------
alter table public.fee_types    enable row level security;
alter table public.student_fees enable row level security;
alter table public.payments     enable row level security;

create policy fee_types_select_school on public.fee_types for select to authenticated
  using (school_id = (select private.app_school_id()));
create policy fee_types_write_finance on public.fee_types for all to authenticated
  using (school_id = (select private.app_school_id()) and (select private.can_manage_finance()))
  with check (school_id = (select private.app_school_id()) and (select private.can_manage_finance()));

create policy student_fees_select on public.student_fees for select to authenticated
  using (
    school_id = (select private.app_school_id())
    and (
      (select private.is_finance_viewer())
      or private.is_parent_of(student_id)
      or private.is_self_student(student_id)
    )
  );
create policy student_fees_write_finance on public.student_fees for all to authenticated
  using (school_id = (select private.app_school_id()) and (select private.can_manage_finance()))
  with check (school_id = (select private.app_school_id()) and (select private.can_manage_finance()));

create policy payments_select on public.payments for select to authenticated
  using (
    school_id = (select private.app_school_id())
    and (
      (select private.is_finance_viewer())
      or private.is_parent_of(student_id)
      or private.is_self_student(student_id)
    )
  );
create policy payments_insert_finance on public.payments for insert to authenticated
  with check (
    school_id = (select private.app_school_id())
    and (select private.can_manage_finance())
    and recorded_by = (select auth.uid())
    and voided_at is null
  );
-- The only permitted update is voiding (column grant below).
create policy payments_void_finance on public.payments for update to authenticated
  using (school_id = (select private.app_school_id()) and (select private.can_manage_finance()))
  with check (school_id = (select private.app_school_id()) and (select private.can_manage_finance()));

revoke update, delete on public.payments from authenticated;
grant update (voided_at, void_reason) on public.payments to authenticated;
